#!/usr/bin/env python3
"""Generates the App Icon catalog for Settings › App Icon (BRAND-02, ADR 0141) from the brand export.

Inputs (the staged brand export, not in git; see docs/design/brand.md §5):
  <export>/icons.json        name, title, group, credit, layers, primary flag per icon
  <export>/previews/*.png    flat 1024 px ictool renders, one per icon
  <export>/icons/*.icon      the Icon Composer packages (copied with --copy-icons)

Outputs (committed):
  Modules/Sources/SettingsFeature/AppIcons/AppIconCatalog+Generated.swift
  Modules/Sources/SettingsFeature/Resources/AppIconThumbnails.xcassets/<name>.imageset   (180 px)
  project.yml   ASSETCATALOG_COMPILER_ALTERNATE_APPICON_NAMES (rewritten in place)
  App/Icons/<name>.icon   only with --copy-icons

Only the icons in SHIPPED (below) are shipped, in that order.

Usage: scripts/brand/gen_app_icons.py [--export DIR] [--copy-icons]
The export defaults to $THESEUS_BRAND_EXPORT, then .scratch/brand/export in this checkout, then in the
main checkout (worktrees share it through git's common dir). Needs ImageMagick (`magick`).
"""
import argparse
import json
import os
import pathlib
import re
import shutil
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
SWIFT_OUT = ROOT / "Modules/Sources/SettingsFeature/AppIcons/AppIconCatalog+Generated.swift"
ASSETS_OUT = ROOT / "Modules/Sources/SettingsFeature/Resources/AppIconThumbnails.xcassets"
ICONS_OUT = ROOT / "App/Icons"
PROJECT = ROOT / "project.yml"
THUMBNAIL_PX = 180

# The icons the app ships, in picker order (the owner's curated 12, ADR 0141 "Size budget"). The brand
# export has 24; each compiled icon costs 1 to 4 MB of Assets.car, so the rest stay in the export.
# This list drives the Swift catalog, the thumbnails, project.yml's alternate names and App/Icons.
SHIPPED = [
    "AppIcon",  # Renoir, the primary
    # Paintings
    "AppIcon-Monet", "AppIcon-VanDijckVerdigris", "AppIcon-CezanneApple", "AppIcon-CezanneBasket",
    "AppIcon-PeetersVerdigris",
    # Cheese
    "AppIcon-PeetersPeek", "AppIcon-BriePeek", "AppIcon-VanDijckTower",
    # Rooms and ledges
    "AppIcon-HammershoiMousehole", "AppIcon-HammershoiSun",
    # Pixel
    "AppIcon-PixelMousehole",
]


def default_export():
    candidates = []
    if os.environ.get("THESEUS_BRAND_EXPORT"):
        candidates.append(pathlib.Path(os.environ["THESEUS_BRAND_EXPORT"]))
    candidates.append(ROOT / ".scratch/brand/export")
    try:
        common = subprocess.run(["git", "-C", str(ROOT), "rev-parse", "--git-common-dir"],
                                capture_output=True, text=True, check=True).stdout.strip()
        candidates.append((ROOT / common).resolve().parent / ".scratch/brand/export")
    except (subprocess.CalledProcessError, FileNotFoundError):
        pass
    for candidate in candidates:
        if (candidate / "icons.json").exists():
            return candidate
    sys.exit("No brand export found; pass --export DIR (it needs icons.json and previews/).")


def swift_string(text):
    return json.dumps(text, ensure_ascii=False)


def case_name(group):
    words = re.findall(r"[A-Za-z0-9]+", group)
    return words[0].lower() + "".join(w.capitalize() for w in words[1:])


def write_swift(icons, groups):
    lines = [
        "// Generated by scripts/brand/gen_app_icons.py from the brand export's icons.json. Don't edit.",
        "",
        "extension AppIconOption {",
        "    /// The picker's sections, in `icons.json` order.",
        "    public enum Group: String, CaseIterable, Hashable, Sendable {",
    ]
    for group in groups:
        lines.append(f"        case {case_name(group)} = {swift_string(group)}")
    lines += ["    }", "}", "", "extension AppIconCatalog {",
              "    /// Every icon the app ships, primary first, in `icons.json` order.",
              "    public static let all: [AppIconOption] = ["]
    for icon in icons:
        lines += [
            "        AppIconOption(",
            f"            name: {swift_string(icon['name'])},",
            f"            title: {swift_string(icon['title'])},",
            f"            group: .{case_name(icon['group'])},",
            f"            credit: {swift_string(icon.get('credit', ''))},",
            f"            isPrimary: {'true' if icon.get('primary') else 'false'}",
            "        ),",
        ]
    lines += ["    ]", "}", ""]
    SWIFT_OUT.parent.mkdir(parents=True, exist_ok=True)
    SWIFT_OUT.write_text("\n".join(lines), encoding="utf-8")


def write_thumbnails(icons, export):
    if ASSETS_OUT.exists():
        shutil.rmtree(ASSETS_OUT)
    ASSETS_OUT.mkdir(parents=True)
    info = {"info": {"author": "xcode", "version": 1}}
    (ASSETS_OUT / "Contents.json").write_text(json.dumps(info, indent=2) + "\n")
    for icon in icons:
        name = icon["name"]
        source = export / "previews" / f"{name}.png"
        if not source.exists():
            sys.exit(f"Missing preview {source}")
        imageset = ASSETS_OUT / f"{name}.imageset"
        imageset.mkdir()
        # The previews already carry the icon's rounded-square mask (transparent corners).
        subprocess.run(["magick", str(source), "-resize", f"{THUMBNAIL_PX}x{THUMBNAIL_PX}", "-depth", "8",
                        "-strip", "-define", "png:compression-level=9", str(imageset / f"{name}.png")], check=True)
        contents = {"images": [{"filename": f"{name}.png", "idiom": "universal"}], **info}
        (imageset / "Contents.json").write_text(json.dumps(contents, indent=2) + "\n")


def update_project(icons):
    alternates = " ".join(icon["name"] for icon in icons if not icon.get("primary"))
    text = PROJECT.read_text(encoding="utf-8")
    pattern = re.compile(r'(ASSETCATALOG_COMPILER_ALTERNATE_APPICON_NAMES: )"[^"]*"')
    if not pattern.search(text):
        sys.exit("project.yml has no ASSETCATALOG_COMPILER_ALTERNATE_APPICON_NAMES line to update")
    PROJECT.write_text(pattern.sub(lambda m: f'{m.group(1)}"{alternates}"', text), encoding="utf-8")


def copy_icons(icons, export):
    ICONS_OUT.mkdir(parents=True, exist_ok=True)
    wanted = {icon["name"] for icon in icons}
    for stale in ICONS_OUT.glob("*.icon"):
        if stale.stem not in wanted:
            shutil.rmtree(stale)
    for name in sorted(wanted):
        target = ICONS_OUT / f"{name}.icon"
        if target.exists():
            shutil.rmtree(target)
        shutil.copytree(export / "icons" / f"{name}.icon", target, ignore=shutil.ignore_patterns(".DS_Store"))


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--export", type=pathlib.Path, help="the brand export directory")
    parser.add_argument("--copy-icons", action="store_true", help="also copy the .icon packages to App/Icons")
    args = parser.parse_args()
    export = args.export or default_export()

    exported = {icon["name"]: icon for icon in json.loads((export / "icons.json").read_text(encoding="utf-8"))}
    missing = [name for name in SHIPPED if name not in exported]
    if missing:
        sys.exit(f"Not in the export's icons.json: {', '.join(missing)}")
    icons = [exported[name] for name in SHIPPED]
    primaries = [icon for icon in icons if icon.get("primary")]
    if len(primaries) != 1 or primaries[0]["name"] != "AppIcon":
        sys.exit("icons.json needs exactly one primary icon, named AppIcon")
    groups = list(dict.fromkeys(icon["group"] for icon in icons))

    write_swift(icons, groups)
    write_thumbnails(icons, export)
    update_project(icons)
    if args.copy_icons:
        copy_icons(icons, export)
    print(f"{len(icons)} of {len(exported)} exported icons in {len(groups)} groups from {export}")


if __name__ == "__main__":
    main()
