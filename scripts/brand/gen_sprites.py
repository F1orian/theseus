#!/usr/bin/env python3
"""Generates DesignSystem's pixel-mouse sprite data from the brand export's sprites.json.

Usage: scripts/brand/gen_sprites.py [path/to/sprites.json]

The default input is scripts/brand/sprites.json (the committed copy of the staged export
`.scratch/brand/export/sprites.json`). The output is
Modules/Sources/DesignSystem/PixelMouseSprites.generated.swift. Never hand-edit the output:
change sprites.json and run this again (ADR 0140).

Rows are emitted exactly as drawn (one character is one pixel, `.` is transparent); `Sprite`
pads short rows on the right with transparency at runtime, and DesignSystemTests check every
glyph is in the palette.

The palette gets one glyph the export doesn't have: `k` (INK_GLYPH), the ink of freestanding marks
(#192: the waiting '?', thought puffs, any detached ink pixel). It's K's umber here, so light mode is
unchanged; `SpriteCanvas` draws it in `PixelMouse.ink`'s light grey in dark mode. Outlines attached to
the mouse or a prop stay `K`.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DEFAULT_INPUT = ROOT / "scripts/brand/sprites.json"
OUTPUT = ROOT / "Modules/Sources/DesignSystem/PixelMouseSprites.generated.swift"

# The pose order the Swift enum uses (brand.md §3), with each pose's purpose for its doc comment.
POSES = {
    "sit": "Default: new chat home, generic.",
    "stand": "Hello: welcome, onboarding, sign-in.",
    "run1": "Thinking / waiting for the first token, frame 1 (with `run2`, ~6 fps).",
    "run2": "Thinking / waiting for the first token, frame 2.",
    "peek": "Peeking over the top edge of a framed artwork: errors, offline, hero art.",
    "read": "Memory, research, knowledge.",
    "lantern": "Incognito, night.",
    "sleep": "Empty states: no chats, no projects, nothing found.",
    "head": "The assistant avatar next to responses, small places.",
}

# Reaction frames and props for petting the mouse (#174): same palette and outline, the same size
# as the pose they vary (so swapping a frame never moves the layout), stepped only.
FRAMES = {
    "headBlink": "`head` with its eyes shut (blink).",
    "headEar": "`head` with its right ear tip twitched outward.",
    "headSniff": "`head` with its nose flared (sniff, alternating with `head`).",
    "sitBlink": "`sit` with its eye shut (blink).",
    "sitEar": "`sit` with its ear tip twitched forward.",
    "sitSniff": "`sit` with its nose poked forward (sniff, alternating with `sit`).",
    "heart": "A tiny pixel heart that floats up from a petted mouse.",
    "crumb": "A cheese crumb that floats up from a petted mouse.",
}

# The ink of freestanding marks (#192), added to the export's palette as K's colour (see the docstring).
INK_GLYPH = "k"


def with_ink(palette: dict[str, str]) -> dict[str, str]:
    """The export's palette plus INK_GLYPH, drawn in K's umber (so light mode stays pixel-identical)."""
    if INK_GLYPH in palette:
        raise SystemExit(f"the export defines {INK_GLYPH!r}; it's reserved for freestanding ink (#192)")
    return {**palette, INK_GLYPH: palette["K"]}


def swift_string(row: str) -> str:
    if not re.fullmatch(r"[A-Za-z.]*", row):
        raise SystemExit(f"unexpected characters in row {row!r}")
    return f'"{row}"'


def main() -> None:
    source = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_INPUT
    data = json.loads(source.read_text(encoding="utf-8"))
    palette: dict[str, str] = with_ink(data["palette"])
    sprites: dict[str, list[str]] = data["sprites"]
    frames: dict[str, list[str]] = data.get("frames", {})

    if set(sprites) != set(POSES):
        raise SystemExit(f"poses differ from the brand spec: {sorted(sprites)} vs {sorted(POSES)}")
    for glyph, colour in palette.items():
        if len(glyph) != 1 or glyph == "." or not re.fullmatch(r"#[0-9A-Fa-f]{6}", colour):
            raise SystemExit(f"bad palette entry {glyph!r}: {colour!r}")
    if set(frames) != set(FRAMES):
        raise SystemExit(f"frames differ from the generator's list: {sorted(frames)} vs {sorted(FRAMES)}")
    for name, rows in {**sprites, **frames}.items():
        unknown = set("".join(rows)) - set(palette) - {"."}
        if unknown:
            raise SystemExit(f"{name} uses glyphs outside the palette: {sorted(unknown)}")

    out: list[str] = [
        "// GENERATED by scripts/brand/gen_sprites.py from scripts/brand/sprites.json. Do not edit.",
        "// One character is one sprite pixel; `.` is transparent (ADR 0140).",
        "",
        "extension PixelMouse {",
        "    /// The sprite palette: Shibata Zeshin's *Mouse* (1847), white coat, grey saddle, rose ears,",
        "    /// umber ink outline. Fixed colours: the mouse looks the same in light and dark, except",
        "    /// `inkGlyph`, which `SpriteCanvas` draws in `ink` (light grey in dark).",
        "    nonisolated static let palette: [Character: RGBA] = [",
    ]
    for glyph, colour in palette.items():
        out.append(f'        "{glyph}": RGBA(hex: 0x{colour[1:].upper()}),')
    out += [
        "    ]",
        "",
        "    /// The ink of freestanding marks (#192): the waiting `?`, thought puffs, detached ink pixels.",
        "    /// It's `K`'s umber in the palette; outlines attached to the mouse or a prop stay `K`.",
        f'    nonisolated static let inkGlyph: Character = "{INK_GLYPH}"',
        "",
        "    nonisolated static func rows(for pose: Pose) -> [String] {",
        "        switch pose {",
    ]
    for name in POSES:
        out.append(f"        case .{name}:")
        out.append("            [")
        for row in sprites[name]:
            out.append(f"                {swift_string(row)},")
        out.append("            ]")
    out += ["        }", "    }", "}", ""]

    out += [
        "extension PixelMouse.Pose {",
        "    /// What each pose is for (brand.md §3).",
        "    public var purpose: String {",
        "        switch self {",
    ]
    for name, purpose in POSES.items():
        out.append(f'        case .{name}: "{purpose}"')
    out += ["        }", "    }", "}", ""]

    out += [
        "extension PixelMouse {",
        "    /// Reaction frames and props for petting the mouse (#174): each frame is the size of the",
        "    /// pose it varies, so swapping it in never moves the layout.",
        "    public enum Frame: String, CaseIterable, Sendable {",
    ]
    for name, purpose in FRAMES.items():
        out.append(f"        /// {purpose}")
        out.append(f"        case {name}")
    out += ["    }", "", "    nonisolated static func rows(for frame: Frame) -> [String] {", "        switch frame {"]
    for name in FRAMES:
        out.append(f"        case .{name}:")
        out.append("            [")
        for row in frames[name]:
            out.append(f"                {swift_string(row)},")
        out.append("            ]")
    out += ["        }", "    }", "}", ""]

    OUTPUT.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)} ({len(POSES)} poses, {len(FRAMES)} frames, {len(palette)} colours)")


if __name__ == "__main__":
    main()
