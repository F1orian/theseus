import DesignSystem
public import Foundation

/// The app's name and version for the Settings info menu and About page (SET-11).
public struct AppInfo: Sendable, Equatable {
    /// `"0.1.0 (7)"`, or `nil` outside an app bundle.
    public let version: String?

    public init(infoDictionary: [String: Any]?) {
        let short = infoDictionary?["CFBundleShortVersionString"] as? String
        let build = infoDictionary?["CFBundleVersion"] as? String
        version = short.map { short in build.map { "\(short) (\($0))" } ?? short }
    }

    public static var current: AppInfo {
        AppInfo(infoDictionary: Bundle.main.infoDictionary)
    }

    /// "Theseus 0.1.0 (7)".
    public var title: String {
        version.map { "Theseus \($0)" } ?? "Theseus"
    }
}

/// Help, project and policy links. They open in the in-app browser.
enum AboutLink: CaseIterable {
    case help
    case support
    case privacyPolicy
    case sourceCode

    var title: String {
        switch self {
        case .help: "Open WebUI help"
        case .support: "Support & feedback"
        case .privacyPolicy: "Privacy policy"
        case .sourceCode: "Source code"
        }
    }

    var systemImage: String {
        switch self {
        case .help: "questionmark.circle"
        case .support: "exclamationmark.bubble"
        case .privacyPolicy: "hand.raised"
        case .sourceCode: "chevron.left.forwardslash.chevron.right"
        }
    }

    var url: URL {
        switch self {
        case .help: URL(string: "https://docs.openwebui.com/") ?? PublicLinks.website
        case .support: PublicLinks.support
        case .privacyPolicy: PublicLinks.privacyPolicy
        case .sourceCode: PublicLinks.repository
        }
    }
}

/// Third-party software and fonts bundled in the app, with their licence texts. The list itself
/// (`Acknowledgement.all`) is generated by `scripts/legal/gen_acknowledgements.py`.
struct Acknowledgement: Identifiable, Sendable {
    let name: String
    /// The bundled version, or empty when it has none.
    let version: String
    let url: URL?
    /// A short licence summary, e.g. "MIT".
    let licenseName: String
    let license: String

    var id: String { name }
}
